/**
 * WP-2.2 — typed event registry: shared types (HISTORY_EVENT_CATALOG §1/§4/§5).
 *
 * The event surface is the frozen contract:
 *  - envelope shape: HISTORY_EVENT_CATALOG §1 (L14-27) +
 *    `schema/history/history-event-envelope.schema.json`;
 *  - the 20-event discriminated union: `schema/history/history-events.schema.json`
 *    (one `oneOf` branch per event; the EVENT TYPE SET is schema-driven — see
 *    registry.ts);
 *  - shared structures (ActorRef / SourceRef / TypedRef / id patterns):
 *    `schema/common.schema.json`;
 *  - emitter matrix (U/A/P), mutation flag (M), owner rule, categories:
 *    HISTORY_EVENT_CATALOG §4 总表;
 *  - per-event payload tables: HISTORY_EVENT_CATALOG §5;
 *  - invariants: ARCHITECTURE.md §5.3 INV-HIST-1..9, INV-TASK-1/3.
 *
 * Layer rules (WP-2.2 boundary): this module is PURE validation + registration
 * metadata — it never rewrites events (no replay, WP-2.3), never writes SQLite
 * (append belongs to the store layer, WP-2.1 schema) and never imports
 * persistence. Every byte of frozen schema JSON flows in through the injected
 * `HistorySchemaReader` (loader pattern, cf. WP-1.1 `ResearchFileReader`);
 * the kernel itself performs no I/O. No DSH imports (INV-PERM-5).
 *
 * NOTE (frozen-contract spelling, see WP-2.2 report): the machine-readable
 * truth `schema/history/history-events.schema.json` names event #8
 * `ACCEPTANCE_CRITERIA_CHANGED`; the semantic document
 * HISTORY_EVENT_CATALOG §4/§5 spells it `ACCEPTANCE_CRITERION_CHANGED`. The
 * registry is schema-driven, so the schema spelling is the canonical
 * eventType here.
 */

