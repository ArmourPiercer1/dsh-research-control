/**
 * The 9-field envelope. `eventType` stays `string` at the envelope level
 * (the schema discriminator is `const` per branch); `EventOf<T>` narrows it.
 * Time fields are epoch ms (memory carrier, DOMAIN_SCHEMA §1.2).
 */
export interface HistoryEventEnvelope<P = unknown> {
  /** H id; unique within the Project, monotonically allocated (§1). */
  eventId: string
  /** The single owner workstream (INV-HIST-3). */
  ownerWorkstreamId: string
  /** Owner-workstream-local sequence, 1..N, assigned at append, never rewritten (INV-HIST-6). */
  eventSeq: number
  /** §4 catalog event type name. */
  eventType: string
  /** Payload schema version; all V1 = 1 (INV-HIST-4). */
  schemaVersion: number
  /** When the real research event happened (epoch ms). Late registration may be older than existing events (§1/§2). */
  occurredAt: number
  /** When the plugin recorded the event (epoch ms); generated by the plugin, never caller-specified (§1). */
  recordedAt: number
  /** Who did it. */
  actor: ActorRef
  /** Where it came from (optional). */
  source?: SourceRef
  /** Strongly typed by (eventType, schemaVersion). */
  payload: P
}

