export const CATALOGS: Record<Locale, Record<CopyKey, string>> = {
  en: COPY_EN,
  zh: COPY_ZH,
}

/**
 * Default-locale table. Kept index-compatible for pre-UI-9 importers
 * that index `COPY_TABLE['key']` directly (tests/views-topology,
 * tests/graph).
 */
export const COPY_TABLE = COPY_EN

/**
 * Locale lookup with `{param}` placeholder substitution (brief #7,
 * UI-9 ADJ-1). `locale` defaults to the module constant so views keep
 * the zero-arg call shape; the locale-aware helpers in `datetime.ts`
 * pass it explicitly. No i18n runtime dependency (no deps rule).
 */
export function t(
  key: CopyKey,
  params?: Record<string, string | number>,
  locale: Locale = LOCALE
): string {
  let out = CATALOGS[locale][key]
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      out = out.split(`{${name}}`).join(String(value))
    }
  }
  return out
}
