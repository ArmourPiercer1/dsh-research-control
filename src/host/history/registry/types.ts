/* ------------------------------------------------------------------ *
 * Structured rejection (precise code + path + message, TC-DOM-027 style)
 * ------------------------------------------------------------------ */

export type EventRejectCode =
  /** Registry failed to load (see HistoryEventRegistry.loadErrors); nothing can be validated. */
  | 'REGISTRY_UNUSABLE'
  /** Envelope field violation (§1) incl. unknown (eventType, schemaVersion) or payload schema failure (INV-HIST-4). */
  | 'ENVELOPE'
  /** actor.kind is not in the event's emitter matrix (catalog §3.6 / §4 E column). */
  | 'EMITTER_FORBIDDEN'
  /** Declared `from` ≠ object's current derived state (INV-HIST-5; TC-HIST-001). */
  | 'FROM_MISMATCH'
  /** Object exists but its current state is not the event's implicit `from` state. */
  | 'WRONG_STATE'
  /** (from, to) not in the §13 legal transition table (INV-TASK-1). */
  | 'ILLEGAL_TRANSITION'
  /** A referenced object does not exist (catalog §5 「payload 内引用的对象存在」). */
  | 'OBJECT_NOT_FOUND'
  /** A "新建" (fresh) id already exists (catalog §5 「新建」). */
  | 'OBJECT_ALREADY_EXISTS'
  /** Owner-workstream rule violation (§4 owner column / INV-HIST-3 / INV-HIST-9). */
  | 'OWNER_MISMATCH'
  /** Payload-internal cross-field rule (WAIVED⇒USER+note, NOT_REQUIRED⇒AC empty, AGENT⇒run_id/created_by_run, relation 组合表, redundancy, payload-vs-edge mirror). */
  | 'CROSS_FIELD'

/** One precisely-located validation error. */
export interface EventValidationError {
  readonly code: EventRejectCode
  /** JSON-pointer path within the event (`/payload/from`, `/actor/kind`); undefined = event-level. */
  readonly path?: string
  readonly message: string
}

/** Structured outcome of `validateEvent` (pure: no write ever occurs). */
export type EventValidationResult =
  | { readonly ok: true; readonly eventType: HistoryEventType; readonly ownerWorkstreamId: string }
  | { readonly ok: false; readonly errors: readonly EventValidationError[] }

