/** The from→to semantics of one event (the 迁移行 of its §5 详细规范). */
export interface EventTransition {
  readonly machine: StateMachine
  /** `payload`: from/to are read from the payload (mutation events, M column ●).
   *  `implicit`: the event declares its `from` implicitly (e.g. RUN_FINISHED requires RUNNING). */
  readonly fromSource: 'payload' | 'implicit'
  /** fromSource=`implicit`: the object's current state must be one of these. */
  readonly expectedFrom?: readonly string[]
}

/**
 * Aggregate (wrapper) semantics — §3.1 atomicity exception + §5.2 batch
 * envelope + §3.7 readability aggregation (INV-HIST-2/8, TC-HIST-007).
 * RUNS_STARTED is the ONLY aggregate event in the V1 catalog.
 */
export interface AggregateRules {
  readonly eventType: 'RUNS_STARTED'
  readonly memberField: 'runs'
  /** schema `minItems: 2` — a single-run launch must use RUN_STARTED. */
  readonly minMembers: 2
  /** §5.2 信封特例: one same-payload event per relevant owner WS. */
  readonly perOwnerEnvelope: true
  /** Run end is always recorded per Run (RUN_FINISHED/FAILED/CANCELLED; no RUNS_FINISHED). */
  readonly runEndsPerRun: true
}

/** One row of the typed registry (20 rows total). */
export interface EventRegistryEntry {
  readonly eventType: HistoryEventType
  /** Payload schema version from the schema branch const (V1: all 1). */
  readonly schemaVersion: number
  readonly category: EventCategory
  /** §4 M column (● = mutation: payload must carry from→to, INV-HIST-5). */
  readonly isMutation: boolean
  /** §4 E column (U/A/P). */
  readonly emitters: readonly EmitterKind[]
  readonly ownerRule: OwnerRule
  /** Present when the event moves a state machine (or a snapshot). */
  readonly transition?: EventTransition
  /** Present only for the aggregate event. */
  readonly aggregate?: AggregateRules
  /** §4 总表 一句话语义. */
  readonly semantics: string
}

/* ------------------------------------------------------------------ *
 * Registry loading (schemaDir injection, loader pattern)
 * ------------------------------------------------------------------ */

/**
 * Read-only schema access (cf. WP-1.1 `ResearchFileReader`, minus `readDir`
 * — the registry reads exactly two files). `readFile` returns `null` for a
 * missing/non-regular path and throws on I/O failure.
 */
export interface HistorySchemaReader {
  readonly readFile: (path: string) => string | null
}

export type HistoryRegistryErrorCode =
  /** A schema file is missing, unreadable, or not valid JSON. */
  | 'SCHEMA_LOAD'
  /** A per-event validator failed to compile. */
  | 'SCHEMA_COMPILE'
  /** The schema's oneOf type set and the §4/§5 metadata disagree (frozen-contract sync check, catalog §7.2). */
  | 'CATALOG_SYNC'

export interface HistoryRegistryLoadError {
  readonly code: HistoryRegistryErrorCode
  readonly file?: string
  readonly message: string
}

/** Outcome of the envelope + payload shape check (§1 + INV-HIST-4, precise AJV errors). */
export type ShapeCheck =
  | { readonly ok: true; readonly eventType: HistoryEventType }
  | { readonly ok: false; readonly errors: readonly EventValidationError[] }

/** The loaded typed event registry (20 events, schema-driven). */
export interface HistoryEventRegistry {
  /** The schemaDir the registry was loaded from. */
  readonly schemaDir: string
  /** False when loadErrors is non-empty; checkShape then reports REGISTRY_UNUSABLE. */
  readonly isUsable: boolean
  readonly loadErrors: readonly HistoryRegistryLoadError[]
  /** All registered event types (schema oneOf order). */
  readonly eventTypes: readonly HistoryEventType[]
  /** eventType → registry entry. */
  readonly events: ReadonlyMap<HistoryEventType, EventRegistryEntry>
  /** Envelope (§1) + payload-discrimination shape check for one candidate event. */
  readonly checkShape: (event: unknown) => ShapeCheck
}
